/**
 * Scans assets/avatars/ and writes js/data/avatars.local.js (bref → file).
 *
 *   node scripts/avatars/build-manifest.mjs
 *
 * File names must be <bref>.webp|png|jpg|jpeg (e.g. jordami01.webp). Anything else in the
 * folder is an error — a typo would otherwise silently show no illustration.
 * The spec for the pictures themselves is docs/AVATAR_SPEC.md.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const AVATAR_DIR = "assets/avatars";
export const MAX_BYTES = 300 * 1024;
const FILE = /^([a-z]{2,10}\d{2})\.(webp|png|jpe?g)$/;
const IGNORED = new Set([".gitkeep"]);

/** ["jordami01.webp", …] → { jordami01: "assets/avatars/jordami01.webp", … } or throws. */
export function manifestFor(files) {
  const manifest = {};
  const bad = [];
  for (const name of [...files].filter((file) => !IGNORED.has(file)).sort()) {
    const match = FILE.exec(name);
    if (!match) {
      bad.push(`${name} — not <bref>.webp|png|jpg`);
      continue;
    }
    const bref = match[1];
    if (manifest[bref]) {
      bad.push(`${name} — ${bref} already has ${manifest[bref].split("/").pop()}`);
      continue;
    }
    manifest[bref] = `${AVATAR_DIR}/${name}`;
  }
  if (bad.length) throw new Error(`assets/avatars has problems:\n  ${bad.join("\n  ")}`);
  return manifest;
}

export function manifestSource(manifest) {
  return `/**
 * AUTO-GENERATED by scripts/avatars/build-manifest.mjs from assets/avatars/ — do not edit by hand.
 * bref → file. Drop an illustration in assets/avatars/<bref>.webp (see docs/AVATAR_SPEC.md) and re-run.
 */

export const LOCAL_AVATARS = ${JSON.stringify(manifest, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL("../../", import.meta.url);
  const manifest = manifestFor(readdirSync(new URL(`${AVATAR_DIR}/`, root)));
  writeFileSync(new URL("js/data/avatars.local.js", root), manifestSource(manifest));
  console.log(`${Object.keys(manifest).length} local illustration(s): ${Object.keys(manifest).join(", ") || "(none yet)"}`);
}
