/**
 * Drops any photos.wiki.js candidate whose file ended up in build-credits.mjs's UNCREDITED list
 * (bad licence, missing author, etc) and records it as a miss instead. The project's policy
 * (see tests/photoPolicy.test.js) is that the photo tables only ever reference files that
 * actually clear the credit check -- a known-uncreditable file shouldn't linger in the data.
 *
 * Run build-credits.mjs first, then this, then build-credits.mjs again to confirm UNCREDITED
 * is empty.
 */
import { writeFileSync } from "node:fs";
import { PHOTO_BY_BREF_WIKI, WIKI_MISSES } from "../../js/data/photos.wiki.js";
import { UNCREDITED } from "../../js/data/photoCredits.js";
import { wikimediaFile } from "../../js/data/photoSource.js";

const OUT = new URL("../../js/data/photos.wiki.js", import.meta.url);
const uncreditedFiles = new Set(Object.keys(UNCREDITED));

const found = {};
const misses = { ...WIKI_MISSES }; // keep every miss discover-wiki.mjs already recorded
let droppedCount = 0;
for (const [bref, url] of Object.entries(PHOTO_BY_BREF_WIKI)) {
  const file = wikimediaFile(url);
  if (file && uncreditedFiles.has(file)) {
    misses[bref] = `uncreditable: ${UNCREDITED[file]}`;
    droppedCount++;
  } else {
    found[bref] = url;
  }
}

writeFileSync(
  OUT,
  `/**
 * AUTO-GENERATED by scripts/photos/discover-wiki.mjs from Wikipedia's batched pageimages API.
 * Lower priority than photos.scraped.js/photos.curated.js (see photo.js's merge order) --
 * these are name-matched automatically, not hand-verified. Still has to clear
 * build-credits.mjs's Commons licence check before it's ever actually shown.
 * ${Object.keys(found).length} candidates found, ${Object.keys(misses).length} misses.
 */

export const PHOTO_BY_BREF_WIKI = ${JSON.stringify(found, null, 2)};

/** bref -> why no candidate was found (debugging aid only). */
export const WIKI_MISSES = ${JSON.stringify(misses, null, 2)};
`
);

console.log(`dropped ${droppedCount} uncreditable candidates, ${Object.keys(found).length} remain`);
for (const [bref, url] of Object.entries(PHOTO_BY_BREF_WIKI)) {
  const file = wikimediaFile(url);
  if (file && uncreditedFiles.has(file)) console.log(`  ${bref}: ${UNCREDITED[file]}`);
}
