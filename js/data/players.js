export function overall(p) {
  const w =
    p.scoring * 0.16 +
    p.defense * 0.12 +
    p.pass * 0.09 +
    p.rebound * 0.09 +
    (p.steal || 50) * 0.05 +
    (p.block || 40) * 0.05 +
    p.speed * 0.07 +
    p.strength * 0.07 +
    p.iq * 0.1 +
    p.clutch * 0.08 +
    p.stamina * 0.05 +
    ((p.three + p.mid + p.paint) / 3) * 0.07;
  return Math.round(w);
}

